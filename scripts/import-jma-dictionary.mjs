#!/usr/bin/env node
// One-off: generate web/content/jma-terms.ts from JMA's multilingual dictionary (多言語辞書, .xlsx).
//
//   curl -o scripts/.data/jma_multilingual.xlsx https://www.data.jma.go.jp/developer/jma_multilingual.xlsx
//   node scripts/import-jma-dictionary.mjs [scripts/.data/jma_multilingual.xlsx]
//   node scripts/import-jma-dictionary.mjs --find 津波警報      # list dictionary rows containing a word
//
// The file is never fetched at runtime or build time. scripts/.data/ is gitignored. Licence: JMA website terms of use
// (https://www.jma.go.jp/jma/kishou/info/coment.html), cited in the generated file. Needs `unzip` on PATH (an .xlsx
// is a zip of XML) and fast-xml-parser from web/.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const { XMLParser } = createRequire(path.join(root, "web/package.json"))("fast-xml-parser");

// The terms our approved notices use, by the dictionary's Japanese entry.
const TERMS = {
  earthquake: "強い地震が発生しました",
  protect: "地震です\n落ち着いて身を守ってください",
  majorTsunamiWarning: "大津波警報",
  tsunamiWarning: "津波警報",
  tsunamiAdvisory: "津波注意報",
  evacuateHighGround: "沿岸部や川沿いにいる人は、ただちに高台や避難ビルなど安全な場所へ避難してください",
  leaveCoast: "海の中にいる人はただちに海から上がって、海岸から離れてください",
  emergencyWarning: "特別警報",
};
// Dictionary column headers (row 1) for the languages Ichido shows. Bengali is not in the dictionary.
const COLUMNS = { ja: "日本語", en: "英語", vi: "ベトナム語", id: "インドネシア語", ne: "ネパール語" };

const args = process.argv.slice(2);
const find = args[0] === "--find" ? args[1] : null;
const file = path.resolve(find ? args[2] ?? "scripts/.data/jma_multilingual.xlsx" : args[0] ?? "scripts/.data/jma_multilingual.xlsx");
const unzip = (entry) => execFileSync("unzip", ["-p", file, entry], { maxBuffer: 64 << 20 }).toString("utf8");
const parser = new XMLParser({ ignoreAttributes: false, attributeNamePrefix: "", processEntities: true, isArray: (n, _p, _leaf, attr) => !attr && ["si", "r", "row", "c"].includes(n) });

const text = (v) => (v == null ? "" : typeof v === "object" ? String(v["#text"] ?? "") : String(v));
const shared = parser.parse(unzip("xl/sharedStrings.xml")).sst.si.map((si) => (si.t != null ? text(si.t) : (si.r ?? []).map((r) => text(r.t)).join("")));
const sheet = parser.parse(unzip("xl/worksheets/sheet2.xml")).worksheet.sheetData.row;
const col = (ref) => ref.replace(/\d+/g, "");
const rows = sheet.map((r) => Object.fromEntries((r.c ?? []).map((c) => [col(c.r), c.t === "s" ? shared[Number(c.v)] : text(c.v ?? c.is?.t)])));
const header = rows[0];
const at = Object.fromEntries(Object.entries(COLUMNS).map(([lang, name]) => {
  const key = Object.keys(header).find((k) => header[k]?.trim() === name);
  if (!key) throw new Error(`column ${name} not found in row 1: ${Object.values(header).join(" | ")}`);
  return [lang, key];
}));
const norm = (s) => s.normalize("NFKC").replace(/\s+/g, "").trim();

if (find) {
  for (const r of rows.filter((r) => r[at.ja]?.includes(find)).slice(0, 40)) console.log(JSON.stringify(Object.fromEntries(Object.entries(at).map(([l, k]) => [l, r[k]]))));
  process.exit(0);
}

const out = {};
for (const [key, ja] of Object.entries(TERMS)) {
  const row = rows.find((r) => norm(r[at.ja] ?? "") === norm(ja));
  if (!row) throw new Error(`term not in the dictionary: ${ja}`);
  out[key] = Object.fromEntries(Object.entries(at).map(([lang, k]) => [lang, (row[k] ?? "").trim()]));
}
const updated = parser.parse(unzip("docProps/core.xml"))["cp:coreProperties"]?.["dcterms:modified"];

const body = `// GENERATED by scripts/import-jma-dictionary.mjs — do not edit by hand.
// Official terms from the Japan Meteorological Agency's multilingual dictionary (気象庁 多言語辞書,
// https://www.data.jma.go.jp/developer/multilingual.html, file modified ${text(updated) || "unknown"}).
// Source: 気象庁ホームページ (Japan Meteorological Agency). Used under the JMA website terms of use
// (https://www.jma.go.jp/jma/kishou/info/coment.html), which permit reuse with the source credited.
// The dictionary has no Bengali: Bengali disaster wording in content/access.ts stays a draft awaiting native review.

export const JMA_TERMS = ${JSON.stringify(out, null, 2)} as const;
`;
writeFileSync(path.join(root, "web/content/jma-terms.ts"), body);
console.log(`wrote web/content/jma-terms.ts (${Object.keys(out).length} terms)`);
